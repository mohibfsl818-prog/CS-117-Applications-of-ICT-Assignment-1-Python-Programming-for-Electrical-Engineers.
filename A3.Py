# RESISTOR COLOUR CODING

colour=input("BAND COLOUR: ").lower()

if colour=='black':
    print('DIGIT=0')
elif colour=='brown':
    print('DIGIT=1')
elif colour=='red':
    print('DIGIT=2')
elif colour=='orange':
    print('DIGIT=3')
elif colour=='yellow':
    print('DIGIT=4')
elif colour=='green':
    print('DIGIT=5')
elif colour=='blue':
    print('DIGIT=6')
elif colour=='violet':
    print('DIGIT=7')
elif colour=='grey':
    print('DIGIT=8')
elif colour=='white':
    print('DIGIT=9')
else:
    print('INVALID COLOUR')
